export type CopyKey = keyof typeof english;

function makeCopy(language: AppLanguage) {
  const copy = (key: CopyKey, ...values: readonly (string | number | bigint)[]) =>
    (language === "en" ? english[key] : key).replace(/\{(\d+)\}/g, (slot, index) =>
      values[index] === undefined ? slot : String(values[index]));
  return Object.assign(copy, { language });
}

const copies = { "zh-HK": makeCopy("zh-HK"), en: makeCopy("en") };
export type Copy = ReturnType<typeof makeCopy>;

export function copyFor(language: AppLanguage): Copy {
  return copies[language];
}

const longDate = { year: "numeric", month: "long", day: "numeric" } as const;
const shortDate = { ...longDate, month: "short" } as const;
const dateTime = { dateStyle: "medium", timeStyle: "short" } as const;
const formats = { long: longDate, short: shortDate, dateTime };
const dateFormatters = new Map<string, Intl.DateTimeFormat>();

export function formatUiDate(t: Copy, value: Date | number, style: keyof typeof formats = "long"): string {
  const date = typeof value === "number" ? new Date(value) : value;
  if (!Number.isFinite(date.getTime())) return t("日期未能讀取");
  const locale = t.language === "en" ? "en-HK" : t.language;
  const key = `${locale}:${style}`;
  let formatter = dateFormatters.get(key);
  if (!formatter) {
    formatter = new Intl.DateTimeFormat(locale, formats[style]);
    dateFormatters.set(key, formatter);
  }
  return formatter.format(date);
}

